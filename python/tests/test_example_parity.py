"""Compare the Python and C++ decks and runs for the example problems.

Each example under ``examples/`` has a ``problem.py`` that builds its deck with
:class:`peridem.Deck`. Two independent things are checked here:

**deck**
    The Python deck against the deck the corresponding C++ driver writes, key
    by key, including every floating-point value. This measures whether the
    Python setup reproduces the C++ setup. It applies only to examples that
    have a C++ driver.

**run**
    The Python deck run twice, once through ``bin/PeriDEM`` in a separate
    process and once through the in-process interface, into separate
    directories, then compared node by node. This measures whether the
    interface and the executable give the same result.

No case reads a deck generated by the C++ side. A deck compared with itself
yields no information.

Run it directly for a table::

    PYTHONPATH=build/linux/python python3 python/tests/test_example_parity.py
    PYTHONPATH=build/linux/python python3 python/tests/test_example_parity.py -k attrition

The two full-size Silling plate cases are skipped unless
``PERIDEM_PARITY_FULL=1`` is set. Their C++ driver takes about 20 minutes to
build the neighbour lists.
"""

