def load_problem(rel: str):
    """Import the ``problem.py`` of an example by path."""
    path = EXAMPLES / rel / "problem.py"
    name = "peridem_example_" + rel.replace("/", "_")
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


@dataclass
class Case:
    """One example, its short-run settings, and its C++ reference driver."""

    name: str
    example: str
    #: kwargs for problem.build_deck for the shortened comparison run
    short: dict[str, Any] = field(default_factory=dict)
    #: C++ driver relative to the build dir, and the args that make it write
    #: the same deck. ``{out}`` / ``{inp}`` are filled in.
    driver: str | None = None
    driver_args: list[str] = field(default_factory=list)
    #: kwargs for build_deck when comparing against that driver's deck
    deck_args: dict[str, Any] = field(default_factory=dict)
    n_threads: int = 1
    heavy: bool = False
    #: "out_inp": driver takes -outputDir/-inputDir separately;
    #: "base": driver takes one -outputDir and makes out/ and inp/ under it.
    driver_layout: str = "out_inp"
    #: False when the example reads committed .msh files rather than meshing
    #: in-process; the run then must not be pointed at an empty mesh dir.
    generates_mesh: bool = True
    #: also check that seeding the pre-notch from Python cuts the same number
    #: of bonds the C++ driver reports
    prenotch: bool = False

    def build(self, mod, output: str, **extra: Any):
        kwargs = dict(self.short)
        kwargs.update(extra)
        # Not every example takes a mesh_dir (some mesh entirely in memory).
        accepted = inspect.signature(mod.build_deck).parameters
        kwargs = {k: v for k, v in kwargs.items() if k in accepted}
        return mod.build_deck(output, **kwargs)


@contextlib.contextmanager
def quiet(log: Path | None):
    """Send the solver's own stdout/stderr to a log file, not the terminal.

    The C++ side writes on file descriptors 1 and 2, so redirecting
    ``sys.stdout`` is not enough.
    """
    if log is None:
        yield
        return
    log.parent.mkdir(parents=True, exist_ok=True)
    sys.stdout.flush()
    sys.stderr.flush()
    saved = os.dup(1), os.dup(2)
    fd = os.open(log, os.O_WRONLY | os.O_CREAT | os.O_TRUNC)
    try:
        os.dup2(fd, 1)
        os.dup2(fd, 2)
        yield
    finally:
        sys.stdout.flush()
        sys.stderr.flush()
        os.dup2(saved[0], 1)
        os.dup2(saved[1], 2)
        for f in (fd, *saved):
            os.close(f)


