def _driver_path(case: Case) -> Path | None:
    if case.driver is None:
        return None
    p = BUILD / case.driver
    return p if p.is_file() and os.access(p, os.X_OK) else None


def check_deck(case: Case, work: Path) -> tuple[str, str]:
    """Run the C++ driver, then diff its deck against the Python one.

    Returns the verdict and the driver's own output.
    """
    import subprocess

    exe = _driver_path(case)
    if exe is None:
        return "no C++ driver", ""
    out, inp = work / "cpp_ref/out", work / "cpp_ref/inp"
    out.mkdir(parents=True, exist_ok=True)
    inp.mkdir(parents=True, exist_ok=True)
    if case.driver_layout == "base":
        cmd = [str(exe), "-nThreads", str(case.n_threads),
               "-outputDir", str(work / "cpp_ref"), *case.driver_args]
    else:
        cmd = [str(exe), "-nThreads", str(case.n_threads),
               "-outputDir", str(out), "-inputDir", str(inp),
               *case.driver_args]
    # -deckOnly stops the driver right after it writes the deck. The
    # pre-notch check needs the bond count the driver reports at init, so
    # those cases let it run (their -finalTime keeps that short).
    if not case.prenotch:
        cmd.append("-deckOnly")
    proc = subprocess.run(cmd, cwd=work, capture_output=True, text=True)
    log = proc.stdout + proc.stderr
    ref = inp / "input.json"
    if not ref.is_file():
        tail = "\n".join(log.splitlines()[-15:])
        raise RuntimeError(f"{case.name}: driver wrote no deck\n{tail}")

    mod = load_problem(case.example)
    py = case.build(mod, str(out) + "/", mesh_dir=inp, **case.deck_args)
    diff = compare_decks(ref, py.to_dict(), rtol=1e-14)
    if not diff.equal:
        raise AssertionError(f"{case.name}: {diff}")
    return "identical", log


def check_prenotch(case: Case, work: Path, driver_log: str) -> str:
    """Seed the pre-notch from Python; compare to the count the driver cut."""
    import re

    m = re.search(r"prenotch=(\d+)", driver_log)
    if not m:
        return "driver reported none"
    expected = int(m.group(1))

    mod = load_problem(case.example)
    inp = work / "prenotch/inp"
    inp.mkdir(parents=True, exist_ok=True)
    deck = case.build(mod, str(work / "prenotch/out") + "/", mesh_dir=inp,
                      **case.deck_args)
    (work / "prenotch/out").mkdir(parents=True, exist_ok=True)
    peridem.init(n_threads=case.n_threads)
    sim = deck.simulation(workdir=work / "prenotch")
    sim.setup()
    got = mod.seed_prenotch(sim, deck.extra_info)
    if got != expected:
        raise AssertionError(
            f"{case.name}: pre-notch cut {got} bonds, C++ cut {expected}")
    return f"{got} bonds"


def check_run(case: Case, work: Path):
    """Run the Python deck through bin/PeriDEM and through the interface."""
    mod = load_problem(case.example)
    extra: dict[str, Any] = {}
    if case.generates_mesh:
        # Generated meshes are written under the temporary directory.
        (work / "meshes").mkdir(parents=True, exist_ok=True)
        extra["mesh_dir"] = work / "meshes"
    deck = case.build(mod, "out/", **extra)
    return run_pair(deck, work / "pair", n_threads=case.n_threads)


def run_case(case: Case, keep: Path | None = None,
             log: bool = False) -> dict[str, Any]:
    root = Path(keep) / case.name if keep else None
    ctx = tempfile.TemporaryDirectory() if root is None else None
    work = root if root is not None else Path(ctx.name)  # type: ignore[union-attr]
    work.mkdir(parents=True, exist_ok=True)
    try:
        with quiet(work / "solver.log" if log else None):
            deck_status, driver_log = check_deck(case, work)
            notch = (check_prenotch(case, work, driver_log)
                     if case.prenotch else "")
            res = check_run(case, work)
        return {"case": case.name, "deck": deck_status, "result": res,
                "prenotch": notch,
                "log": work / "solver.log" if log else None}
    finally:
        if ctx is not None:
            ctx.cleanup()


