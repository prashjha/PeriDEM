def main(argv: list[str] | None = None) -> int:
    import argparse

    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("-k", "--select", action="append", default=[],
                   help="only cases whose name contains this (repeatable)")
    p.add_argument("--full", action="store_true",
                   help="include the heavy full-size cases")
    p.add_argument("--keep", metavar="DIR", default=None,
                   help="keep the run directories under DIR")
    p.add_argument("-v", "--verbose", action="store_true",
                   help="let the solver write to the terminal")
    args = p.parse_args(argv)

    cases = [c for c in CASES if args.full or FULL or not c.heavy]
    if args.select:
        cases = [c for c in cases
                 if any(s in c.name for s in args.select)]
    if not cases:
        print("no cases selected", file=sys.stderr)
        return 2

    try:
        exe = find_peridem_binary()
    except FileNotFoundError as exc:
        print(exc, file=sys.stderr)
        return 2
    print(f"peridem {peridem.version()}   bin/PeriDEM {exe}\n")

    rows: list[tuple[str, str, str, str, str]] = []
    failures = 0
    for case in cases:
        print(f"[{case.name}] ...", flush=True)
        try:
            info = run_case(case, keep=Path(args.keep) if args.keep else None,
                            log=not args.verbose)
        except Exception as exc:  # noqa: BLE001 - report and continue
            failures += 1
            rows.append((case.name, "ERROR", "-", "-",
                         str(exc).splitlines()[0]))
            print(f"  FAILED: {exc}", file=sys.stderr)
            continue
        res = info["result"]
        ok = res.max_linf == 0.0
        failures += 0 if ok else 1
        nodes = int(next(iter(res.report.values()))["n"]) if res.report else 0
        rows.append((case.name, info["deck"], info.get("prenotch") or "-",
                     f"{nodes}", f"{res.max_linf:.3e}"))
        print(res.table(case.name))
        print()

    width = max(len(r[0]) for r in rows) + 2
    total = width + 60
    print("=" * total)
    print(f"{'case':<{width}}{'deck vs C++':<16}{'prenotch':<16}"
          f"{'nodes':>8}{'max Linf':>16}")
    print("-" * total)
    for name, deck, notch, nodes, linf in rows:
        print(f"{name:<{width}}{deck:<16}{notch:<16}{nodes:>8}{linf:>16}")
    print("=" * total)
    print("all identical" if failures == 0 else f"{failures} case(s) failed")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
